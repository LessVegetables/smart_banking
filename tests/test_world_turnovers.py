def test_world_covers_every_data_quality_tier(world, mature):
    tiers = Counter(map(_tier, world.companies))
    assert all(tiers[t] / len(world.companies) > 0.03 for t in ('FULL', 'PARTIAL', 'THIN'))
    assert sum(_tier(x) == 'FULL' for x in mature) / len(mature) > 0.8


def test_counterparties(world):
    for x in world.companies:
        cp = x.accounts.counterparties_12m
        if _receipts(_last12(x)) == 0:
            assert cp.customers_count == 0 and cp.top_customer_share is None
        else:
            assert cp.customers_count >= 1 and cp.top_customer_share >= 1 / cp.customers_count - 0.001
    sole = [x for x in world.companies if x.accounts.counterparties_12m.customers_count == 1]
    assert all(x.accounts.counterparties_12m.top_customer_share == 1.0 for x in sole)


def test_loans(world):
    with_loans = [x for x in world.companies if x.loans]
    assert 0.3 < len(with_loans) / len(world.companies) < 0.5
    weak = [x for x in world.companies if x.q < -1]
    strong = [x for x in world.companies if x.q > 1]
    assert sum(bool(x.loans) for x in weak) / len(weak) > sum(bool(x.loans) for x in strong) / len(strong)
    for x in with_loans:
        assert len({loan.loan_id for loan in x.loans}) == len(x.loans)
        for loan in x.loans:
            assert x.egrul.registered_at + timedelta(days=90) <= loan.opened_at < AS_OF
            assert loan.monthly_payment == annuity(loan.amount, loan.rate, loan.term_months)
            assert loan.balance_after(0) == loan.amount and loan.balance_after(loan.term_months) < 100
            assert loan.kind == 'loan' or x.legal_form == c.LegalForm.OOO


def test_loans_are_paid_through_the_account(world):
    # The account shows the actual payments: the schedule, moved by late payments (T03).
    for x in world.companies:
        paid = payments_by_month(x.loans)
        for m in x.accounts.months:
            index = month_index(date.fromisoformat(m.month + '-01'))
            assert m.outflows.loan_payments == paid[index]
            assert m.inflows.loans_received == sum(l.amount for l in x.loans
                                                   if l.kind == 'loan' and month_index(l.opened_at) == index)
