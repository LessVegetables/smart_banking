def test_months_cover_the_open_account(world):
    last = month_index(AS_OF) - 1
    for x in world.companies:
        a = x.accounts
        assert x.egrul.registered_at <= a.account_opened_at < AS_OF
        assert len(a.months) == min(24, max(0, last - first_full_month(a.account_opened_at) + 1))
        if a.months:
            assert a.months[-1].month == month_name(last)
        for m in a.months:
            assert m.average_balance >= 0


def test_receipts_follow_revenue(mature):
    cashless = [x for x in mature if x.industry in {'wholesale', 'it', 'manufacturing', 'construction'}]
    ratios = [_receipts(_last12(x)) / x.annual_revenue for x in cashless]
    assert 0.93 < statistics.median(ratios) < 1.05
    cash_heavy = [_receipts(_last12(x)) / x.annual_revenue for x in mature if x.industry == 'beauty']
    assert statistics.median(cash_heavy) < statistics.median(ratios) - 0.1


def test_receipts_follow_seasonality(mature):
    by_month = Counter()
    for x in mature:
        if x.industry == 'agriculture':
            for m in _last12(x):
                by_month[m.month[-2:]] += m.inflows.customers
    assert by_month['08'] + by_month['09'] > 3 * (by_month['01'] + by_month['02'])


def test_receipts_follow_trend(mature):
    def ratio(x):
        return _receipts(x.accounts.months[-12:]) / max(1, _receipts(x.accounts.months[:12]))
    # Young companies are still ramping up, so compare those that are at least three years old.
    old = [x for x in mature if (AS_OF - x.egrul.registered_at).days > 3 * 365]
    growing = [ratio(x) for x in old if x.revenue_growth > 0.2]
    shrinking = [ratio(x) for x in old if x.revenue_growth < -0.1]
    assert statistics.median(growing) > 1.12 and statistics.median(shrinking) < 0.95


def test_quality_drives_account_behaviour(mature):
    weak = [x for x in mature if x.q < -1]
    strong = [x for x in mature if x.q > 1]

    def cv(x):
        values = [m.inflows.customers for m in _last12(x)]
        return statistics.pstdev(values) / statistics.mean(values) if any(values) else 1.0

    def owner_money(x):
        months = _last12(x)
        total = sum(m.inflows.total for m in months)
        return sum(m.inflows.founder_contributions + m.inflows.own_transfers for m in months) / total

    def gaps(x):
        return sum(m.inflows.customers == 0 for m in x.accounts.months)

    def cushion(x):  # average balance in days of spending
        months = _last12(x)
        return statistics.mean(m.average_balance for m in months) / (sum(m.outflows.total for m in months) / 365)

    mean = lambda f, group: statistics.mean(map(f, group))
    assert statistics.median(map(cv, weak)) > 1.5 * statistics.median(map(cv, strong))
    assert mean(owner_money, weak) > 3 * mean(owner_money, strong)
    assert mean(gaps, weak) > 10 * mean(gaps, strong)
    assert statistics.median(map(cushion, strong)) > 1.5 * statistics.median(map(cushion, weak))


def test_tax_debt_shows_as_missed_tax_payments(mature):
    def paid_share(group):
        return statistics.mean(sum(m.outflows.taxes > 0 for m in x.accounts.months[-6:]) / 6 for x in group)
    debtors = [x for x in mature if x.fns.tax_debt > 0]
    payers = [x for x in mature if x.fns.tax_debt == 0]
    assert paid_share(debtors) < paid_share(payers) - 0.2


