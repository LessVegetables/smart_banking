AS_OF = date(2026, 10, 1)


@pytest.fixture(scope='module')
def world():
    return generate_world(seed=7, n=3000, as_of=AS_OF)


@pytest.fixture(scope='module')
def mature(world):
    # Accounts as T02 builds them: no shells and no clients with incomplete data (T04).
    return [x for x in world.companies if len(x.accounts.months) == 24 and x.archetype in ('regular', 'inflater')]


def _last12(x):
    return x.accounts.months[-12:]


def _receipts(months):
    return sum(m.inflows.customers for m in months)


def _tier(x) -> c.DataQualityTier:
    return data_quality(SourcePayloads.from_company(x), x.declared_annual_revenue).tier


def test_t01_data_is_unchanged():
    # Hash of the companies without loans, accounts and bureau reports, generated by the T03 code on main.
    # Only a shell company (T04) gets new registry data. The outcome (T05) and the other sources (T06) are new data.
    world = generate_world(seed=11, n=300, as_of=AS_OF)
    exclude = {'archetype', 'declared_annual_revenue', 'loans', 'accounts', 'bki', 'pd_12m', 'default_12m', 'sample',
               'client_card', 'fssp', 'arbitration', 'aml'}
    dump = '\n'.join(x.model_dump_json(exclude=exclude) for x in world.companies if x.archetype != 'shell')
    assert hashlib.sha256(dump.encode()).hexdigest() == \
        'd08584510ad525dfbb6af21aa0aeb6fc3dcb13a75bfdc5bffc38eb2a696d25f3'


